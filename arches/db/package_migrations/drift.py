"""Refuse to apply a plan to a graph that is not where history says it is.

Package migrations are generated by diffing committed JSON against replayed
migration history -- never against the site's database. That is what makes
generation reproducible, and it is also the assumption Django can rely on and
Arches cannot: a graph is rows a curator can edit in the Graph Designer at
runtime.

On a graph that has diverged, the failures are silent. An AlterNode for a node
the site deleted updates zero rows and reports success. A CreateNode for a node
the site already added collides, or quietly writes over it.

So before applying, check the rows the plan is about to write: whether they are
there, not what they contain. Field-level comparison is deliberately out of scope
-- it needs a three-way merge against the last-applied package snapshot, and it
would report false conflicts for i18n fields, which serialize per active language.
"""

from arches.app.models import models
from arches.db.package_migrations.operations.base import (
    _AlterRowOperation,
    _CreateRowOperation,
    _DeleteRowOperation,
)
from arches.db.package_migrations.operations.graph import CreateGraph


def problems(plan, using):
    """Human-readable reasons this plan does not fit this database."""
    found = []
    for migration, backwards in plan:
        if backwards:
            # Unapplying recreates rows from replayed state, so the forward
            # expectations do not hold in reverse.
            continue
        for operation in migration.operations:
            reason = _problem(operation, using)
            if reason:
                found.append(
                    "%s.%s: %s" % (migration.app_label, migration.name, reason)
                )
    return found


def _problem(operation, using):
    if isinstance(operation, CreateGraph):
        if _exists(models.GraphModel, operation.graphid, using):
            return "graph %s already exists" % operation.graphid
        return None

    model = getattr(operation, "model", None)
    if model is None:
        return None

    if isinstance(operation, _CreateRowOperation):
        if _exists(model, operation._pk, using):
            return "%s %s already exists" % (model.__name__, operation._pk)
    elif isinstance(operation, (_AlterRowOperation, _DeleteRowOperation)):
        if not _exists(model, operation._pk, using):
            return "%s %s is missing" % (model.__name__, operation._pk)
    return None


def _exists(model, pk, using):
    return model.objects.using(using).filter(pk=pk).exists()
